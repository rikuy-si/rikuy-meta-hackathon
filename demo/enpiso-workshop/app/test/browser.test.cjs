// Visible text plus accessible names (aria-label, title, alt) of everything in the shown view, the <title> and the meta description.
const pageCopy = () => {
  const vis = (e) => !e.closest('[hidden]') && e.getClientRects().length > 0;
  const attrs = [...document.querySelectorAll('[aria-label],[title],img[alt]')].filter((e) => vis(e) || e.tagName === 'VIDEO')
    .flatMap((e) => ['aria-label', 'title', 'alt'].map((a) => e.getAttribute(a)).filter(Boolean));
  // text generated by CSS (content: on ::before / ::after), which innerText leaves out
  const css = [...document.querySelectorAll('body *')].filter(vis).flatMap((e) => ['::before', '::after'].map((p) => getComputedStyle(e, p).content))
    .filter((c) => /^".{2,}"$/.test(c)).map((c) => JSON.parse(c));
  return [document.body.innerText, ...attrs, ...new Set(css), document.title, document.querySelector('meta[name=description]').content].join('\n');
};
async function leftovers(page, lang) {
  return page.evaluate(([src, lang, get]) => {
    const text = new Function(`return (${get})()`)().replace(/EnPiso Visión|Visión|[PLANT]|[MODULE]|Español|English/g, ' ');
    const re = new RegExp(src, 'gi'), hits = new Set();
    for (const line of text.split('\n')) { const m = line.match(re); if (m) m.forEach((w) => hits.add(`${w} ← ${line.trim().slice(0, 70)}`)); }
    return [...hits].slice(0, 8);
  }, [LEFTOVER[lang], lang, pageCopy.toString()]);
}
