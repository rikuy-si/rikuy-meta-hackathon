  // 1. a Spanish browser, ?lang=en wins, and the choice persists
  const ctx = await newContext(browser, vp, 'es-CO');
  await ctx.addInitScript(recordCanvasText);
  const page = await ctx.newPage(); watchErrors(page);
  await page.goto(url('#/panel', { lang: 'en' }), { waitUntil: 'domcontentloaded' });
  await page.waitForSelector('#top-insights .insight');
  let s = await state(page);
  check(`${tag}: ?lang=en opens in English on a Spanish browser`, s.html === 'en-US' && s.first === E.en.first && s.title === E.en.title, s);
  check(`${tag}: the lang deep link is saved`, s.saved === 'en', s.saved);
  const freshEn = await panelText(page);
  await page.goto(url('#/panel'), { waitUntil: 'domcontentloaded' });
  await page.waitForSelector('#top-insights .insight');
  s = await state(page);
