  await page.locator('#eficiencia').scrollIntoViewIfNeeded();
  const yBefore = await page.evaluate(() => document.getElementById('eficiencia').getBoundingClientRect().top);
  // the header is not sticky, so a pointer click scrolls to the top first; activate the switch in place to check the anchoring
  await page.evaluate(() => document.querySelector('[data-lang="en"]').click());
  await wait(300);
  const kept = await page.evaluate(() => ({ open: document.querySelector('#top-insights details.how').open, top: document.getElementById('eficiencia').getBoundingClientRect().top }));
  check(`${tag}: switching keeps open panels and the reading position`, kept.open && Math.abs(kept.top - yBefore) < 60, { ...kept, yBefore });
  await page.locator('#top-insights details.how').first().locator('summary').click();
  const toggledEn = await panelText(page), enLeft = await leftovers(page, 'en');
  check(`${tag}: no Spanish left after switching to EN`, enLeft.length === 0, enLeft);
  check(`${tag}: switched EN panel reads exactly like a fresh EN load`, toggledEn === freshEn, toggledEn === freshEn ? undefined : firstDiff(toggledEn, freshEn));
  await page.locator('#eficiencia .tip[data-tip="takt"], #ejemplo .tip[data-tip="takt"]').first().click();
  check(`${tag}: tooltips follow the language`, await page.evaluate(() => /How often a piece/.test(document.getElementById('tip-pop').textContent)));
  await page.keyboard.press('Escape');

  // 3. the video keeps playing through a switch: same element, same source, same position, layers and clip kept
  await page.goto(url('#/video?t=2455&clip=2455-2530&from=restriccion&capas=zonas,puestos&lang=en'), { waitUntil: 'domcontentloaded' });
  await until(page, videoReady, 2455, 45000);
