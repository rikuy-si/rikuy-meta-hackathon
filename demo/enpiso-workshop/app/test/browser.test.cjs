  const sp = (extra) => { const q = new URLSearchParams(R2 ? '' : 'src=local'); for (const [k, v] of Object.entries(extra || {})) q.set(k, v); const s = q.toString(); return s ? `?${s}` : ''; };
  const url = (hash, extra) => `${base}${sp(extra)}${hash}`;
  const errors = [];
  const watchErrors = (page) => { page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); }); page.on('pageerror', (e) => errors.push(String(e))); };
  const state = (page) => page.evaluate(() => ({ html: document.documentElement.lang, saved: localStorage.getItem('enpiso-vision-lang'), search: location.search, hash: location.hash, title: document.title,
    first: document.querySelector('#top-insights .insight h3') && document.querySelector('#top-insights .insight h3').textContent }));
