  await page.waitForSelector('#top-insights .insight');
  const freshEs = await panelText(page);
  check(`${tag}: switched ES panel reads exactly like a fresh ES load`, toggledEs === freshEs, toggledEs === freshEs ? undefined : firstDiff(toggledEs, freshEs));
  // open a "How did we measure this?" panel and scroll down: both survive the switch
