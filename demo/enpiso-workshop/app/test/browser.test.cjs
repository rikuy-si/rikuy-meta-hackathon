  check(`${tag}: ES toggle switches the page, the hash and the saved choice`, s.html === 'es-CO' && s.first === E.es.first && s.title === E.es.title && /lang=es/.test(s.hash) && !/lang=/.test(s.search) && s.saved === 'es', s);
